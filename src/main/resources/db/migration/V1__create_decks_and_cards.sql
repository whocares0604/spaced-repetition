CREATE TABLE deck (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(255) NOT NULL,
                      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE card (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      deck_id BIGINT NOT NULL REFERENCES deck(id),
                      front TEXT NOT NULL,
                      back TEXT NOT NULL,
                      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);